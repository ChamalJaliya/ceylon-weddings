"""Generate packages/ui/src/styles/palettes.css from Kloqra's optional palettes.

Usage: python3 -I gen_palettes.py <kloqra tokens.css> <out palettes.css>
Kloqra's brand blue is NOT imported — only its optional palettes.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()
NAMES = ["modern", "aurora", "noir", "sunset", "forest-walnut", "bordeaux-taupe", "midnight-ivory", "olive-linen"]
KEYS = ["accent", "accent-hover", "accent-active", "subtle", "heading", "body", "page", "card", "border",
        "dark-accent", "dark-heading", "dark-body", "dark-page", "dark-card", "dark-fg"]

prims = {}
for name in NAMES:
    for key in KEYS:
        m = re.search(rf"--palette-{name}-{key}:\s*(#[0-9a-fA-F]{{3,8}});", text)
        if m:
            prims[(name, key)] = m.group(1).lower()
    missing = [k for k in KEYS if k != "dark-fg" and (name, k) not in prims]
    assert not missing, (name, missing)

# Ceylon's own Temple palette (sandalwood + kumkum maroon) — light uses existing
# --cw-* primitives in tokens.css; dark needs new values.
TEMPLE_DARK = {
    "dark-accent": "#e89aaa",
    "dark-heading": "#f6ebe0",
    "dark-body": "#c9b3a3",
    "dark-page": "#1a100c",
    "dark-card": "#251812",
}

lines = []
w = lines.append
w("/*")
w(" * Colour palettes (ported from Kloqra's optional palettes; Kloqra's brand blue is not used).")
w(" * Generated by scripts/gen-palettes.py from Kloqra's palette primitives; safe to hand-edit, keep")
w(" * the semantic blocks in sync. Each palette composes with light (pearl) and dark (night) mode:")
w(" *   <html class=\"night\" data-palette=\"aurora\">")
w(" * Palette blocks only reassign semantic tokens; status colours stay with the mode.")
w(" */")
w("")
w(":root {")
for name in NAMES:
    for key in KEYS:
        if (name, key) in prims:
            w(f"  --pal-{name}-{key}: {prims[(name, key)]};")
    w("")
for key, value in TEMPLE_DARK.items():
    w(f"  --pal-temple-{key}: {value};")
w("}")
w("")


def light_block(sel, p):
    return [
        f"{sel} {{",
        f"  --color-primary: {p['accent']};",
        f"  --color-primary-hover: {p['accent-hover']};",
        f"  --color-primary-active: {p['accent-active']};",
        f"  --color-primary-subtle: {p['subtle']};",
        f"  --color-primary-fg: var(--cw-white);",
        f"  --color-primary-text: {p['accent-hover']};",
        f"  --color-text-heading: {p['heading']};",
        f"  --color-text-body: {p['body']};",
        f"  --color-text-muted: color-mix(in srgb, {p['body']} 88%, {p['page']});",
        f"  --color-text-inverse: {p['card']};",
        f"  --color-bg-page: {p['page']};",
        f"  --color-bg-card: {p['card']};",
        f"  --color-bg-muted: color-mix(in srgb, {p['subtle']} 45%, {p['page']});",
        f"  --color-bg-accent: {p['subtle']};",
        f"  --color-bg-sidebar: color-mix(in srgb, {p['subtle']} 40%, {p['card']});",
        f"  --color-bg-inset: color-mix(in srgb, {p['page']} 70%, {p['subtle']});",
        f"  --color-border: {p['border']};",
        f"  --color-border-strong: color-mix(in srgb, {p['border']} 70%, {p['body']});",
        f"  --color-focus-ring: {p['accent']};",
        f"  --color-secondary: color-mix(in srgb, {p['subtle']} 70%, {p['card']});",
        f"  --color-secondary-fg: {p['accent-active']};",
        f"  --color-frame: color-mix(in srgb, {p['subtle']} 65%, {p['page']});",
        f"  --color-chart-1: {p['accent']};",
        "}",
        "",
    ]


def dark_block(sel, p, fg):
    return [
        f"{sel} {{",
        f"  --color-primary: {p['dark-accent']};",
        f"  --color-primary-hover: color-mix(in srgb, {p['dark-accent']} 85%, var(--cw-white));",
        f"  --color-primary-active: {p['dark-accent']};",
        f"  --color-primary-subtle: color-mix(in srgb, {p['dark-accent']} 16%, transparent);",
        f"  --color-primary-fg: {fg};",
        f"  --color-primary-text: {p['dark-accent']};",
        f"  --color-text-heading: {p['dark-heading']};",
        f"  --color-text-body: color-mix(in srgb, {p['dark-heading']} 86%, {p['dark-body']});",
        f"  --color-text-muted: color-mix(in srgb, {p['dark-heading']} 62%, {p['dark-body']});",
        f"  --color-text-inverse: {p['dark-page']};",
        f"  --color-bg-page: {p['dark-page']};",
        f"  --color-bg-card: {p['dark-card']};",
        f"  --color-bg-muted: color-mix(in srgb, {p['dark-card']} 88%, {p['dark-heading']});",
        f"  --color-bg-accent: color-mix(in srgb, {p['dark-accent']} 14%, {p['dark-card']});",
        f"  --color-bg-sidebar: color-mix(in srgb, {p['dark-accent']} 6%, {p['dark-page']});",
        f"  --color-bg-inset: color-mix(in srgb, {p['dark-page']} 70%, {p['dark-card']});",
        f"  --color-border: color-mix(in srgb, {p['dark-heading']} 14%, transparent);",
        f"  --color-border-strong: color-mix(in srgb, {p['dark-heading']} 24%, transparent);",
        f"  --color-focus-ring: {p['dark-accent']};",
        f"  --color-secondary: color-mix(in srgb, {p['dark-accent']} 14%, {p['dark-card']});",
        f"  --color-secondary-fg: {p['dark-heading']};",
        f"  --color-frame: color-mix(in srgb, {p['dark-page']} 70%, var(--cw-black));",
        f"  --color-chart-1: {p['dark-accent']};",
        "}",
        "",
    ]


for name in NAMES:
    p = {k: f"var(--pal-{name}-{k})" for k in KEYS if (name, k) in prims}
    fg = p.get("dark-fg", p["dark-page"])
    w(f"/* ── {name.replace('-', ' ').title()} ── */")
    lines.extend(light_block(f'[data-palette="{name}"]', p))
    lines.extend(dark_block(f'.night[data-palette="{name}"],\n[data-palette="{name}"] .night:not([data-palette]),\n.night [data-palette="{name}"]:not(.pearl)', p, fg))

# Temple: light from existing Ceylon primitives, dark from the new ones.
temple = {
    "accent": "var(--cw-maroon-700)", "accent-hover": "var(--cw-maroon-800)", "accent-active": "var(--cw-maroon-900)",
    "subtle": "var(--cw-maroon-100)", "heading": "var(--cw-sandal-ink-900)", "body": "var(--cw-sandal-ink-700)",
    "page": "var(--cw-sandal-100)", "card": "var(--cw-sandal-50)", "border": "var(--cw-sandal-300)",
    **{k: f"var(--pal-temple-{k})" for k in TEMPLE_DARK},
}
w("/* ── Temple (Ceylon): sandalwood + kumkum maroon ── */")
lines.extend(light_block('[data-palette="temple"]', temple))
lines.extend(dark_block('.night[data-palette="temple"],\n[data-palette="temple"] .night:not([data-palette]),\n.night [data-palette="temple"]:not(.pearl)', temple, temple["dark-page"]))

open(out, "w").write("\n".join(lines).rstrip() + "\n")
print("wrote", out, len(lines), "lines")
